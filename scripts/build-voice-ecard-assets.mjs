#!/usr/bin/env node
// Writes src/artifacts/voice-ecard-assets.ts from the WebP textures in assets/voice-ecard/.
//
// The voice eCard's envelope paper, its liner and the letter's paper are carried INSIDE the package as
// data URIs, so a host has nothing to copy into public/, no route to mount and no font-style
// tracing trap to fall into: a voice eCard page draws by construction on any host. Only the one envelope
// and the one liner a card uses reach its page, once, in a <style> rule.
//
// Provenance: the textures are BlessOut's (public/graphics/envelope/*.png, inner/*.png and
// letter-background.png), the same images the BlessOut card opening draws, reduced with
//   cwebp -q 76 -resize 640 640 <envelope>.png      (envelopes, 1000x1000 -> 640x640)
//   cwebp -q 76 <liner>.png                          (liners, unchanged size)
//   cwebp -q 72 -resize 900 0 letter-background.png  (the letter's paper)
// Re-run this script after replacing a file in assets/voice-ecard/.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'assets', 'voice-ecard')
const files = readdirSync(dir).filter((f) => f.endsWith('.webp')).sort()
const uri = (f) => `data:image/webp;base64,${readFileSync(join(dir, f)).toString('base64')}`
const pick = (prefix) => files.filter((f) => f.startsWith(prefix)).map((f) => [f.slice(prefix.length, -'.webp'.length), uri(f)])

const envelopes = pick('env-')
const liners = pick('liner-')
const paper = files.includes('paper.webp') ? uri('paper.webp') : null
if (!envelopes.length || !liners.length || !paper) throw new Error('assets/voice-ecard/ needs env-*.webp, liner-*.webp and paper.webp')

const obj = (entries) => `{\n${entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}\n}`
const out = `// GENERATED by scripts/build-voice-ecard-assets.mjs from assets/voice-ecard/. Do not edit by hand.
// The voice eCard's textures as data URIs (BlessOut's envelope papers, liners and letter paper, as WebP).

/** Envelope paper by colour name. */
export const ENVELOPE_PAPER: Record<string, string> = ${obj(envelopes)}

/** Envelope liner by pattern name. */
export const LINER_PAPER: Record<string, string> = ${obj(liners)}

/** The letter's paper: the card's inside pages and the letter peeking from the envelope. */
export const LETTER_PAPER = ${JSON.stringify(paper)}
`
writeFileSync(join(root, 'src', 'artifacts', 'voice-ecard-assets.ts'), out)
console.log(`voice-ecard-assets.ts: ${envelopes.length} envelopes, ${liners.length} liners, paper; ${Math.round(out.length / 1024)} KB`)
